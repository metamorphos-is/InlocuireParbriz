## Original, OEM și aftermarket

- **Original (de la dealer):** parbrizul vine prin rețeaua mărcii auto și are, de regulă, sigla constructorului pe marcaj.
- **OEM:** sticlă făcută de același producător care livrează fabricii, pe aceleași specificații, dar vândută fără sigla mărcii auto. Diferența de preț față de original poate fi semnificativă.
